CREATE TABLE employees (
    EmployeeNumber INT,
    Age INT,
    Department VARCHAR(100),
    JobRole VARCHAR(100),
    MonthlyIncome INT,
    OverTime VARCHAR(10),
    JobSatisfaction INT,
    YearsAtCompany INT,
    WorkLifeBalance INT,
    PerformanceRating INT,
    YearsSinceLastPromotion INT,
    Attrition VARCHAR(10)
);

